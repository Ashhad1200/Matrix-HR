#!/usr/bin/env python3
"""Turns `prisma migrate diff --script` output into an additive, idempotent migration (stdout)."""
import re, sys
raw = open(sys.argv[1]).read()
strip = lambda x: "\n".join(l for l in x.split("\n") if not l.startswith("--")).strip()
guard = lambda st: "DO $$ BEGIN\n  %s;\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $$;" % st
out = []
for st in (strip(x) for x in re.split(r";\s*\n", raw)):
    if not st: continue
    if st.startswith("CREATE TYPE"): out.append(guard(st))
    elif st.startswith("CREATE TABLE"): out.append(st.replace("CREATE TABLE", "CREATE TABLE IF NOT EXISTS", 1) + ";")
    elif st.startswith("CREATE UNIQUE INDEX"): out.append(st.replace("CREATE UNIQUE INDEX", "CREATE UNIQUE INDEX IF NOT EXISTS", 1) + ";")
    elif st.startswith("CREATE INDEX"): out.append(st.replace("CREATE INDEX", "CREATE INDEX IF NOT EXISTS", 1) + ";")
    elif st.startswith("ALTER TABLE") and "ADD COLUMN" in st: out.append(st.replace("ADD COLUMN", "ADD COLUMN IF NOT EXISTS") + ";")
    elif st.startswith("ALTER TABLE") and "ADD CONSTRAINT" in st: out.append(guard(st))
    else: sys.exit("unhandled statement: " + st[:100])
hdr = """-- 1_ai_billing: manual payments, billing lifecycle, staff invites, email outbox, AI assistant.
--
-- ADDITIVE AND IDEMPOTENT. Every statement is guarded (IF NOT EXISTS / duplicate_object), so it is safe to apply
-- to a database that already has some of these objects (e.g. built with `prisma db push`) and safe to apply twice.
-- It contains no destructive statements (no table or column removal, no renames, no column type changes). It also creates
-- the ExpenseCategory/ExpenseClaim/ExpenseItem/LoanRequest tables and CompensationItem.sourceType/sourceId that 0_init never
-- had (a no-op where they already exist).
-- Generated by scripts/gen-migration.sh (prisma migrate diff, then scripts/idempotent-migration.py).

"""
extra = """
-- One open (awaiting proof or pending) request per tenant per purpose. Prisma cannot express partial indexes.
CREATE UNIQUE INDEX IF NOT EXISTS "PaymentRequest_one_open_per_purpose"
  ON "PaymentRequest" ("tenantId", "purpose") WHERE "status" IN ('AWAITING_PROOF', 'PENDING');

-- One live invitation per employee: resending revokes the old one first.
CREATE UNIQUE INDEX IF NOT EXISTS "UserInvite_one_live_per_employee"
  ON "UserInvite" ("employeeId") WHERE "usedAt" IS NULL AND "revokedAt" IS NULL;

-- Zero or negative prices are never valid.
DO $$ BEGIN
  ALTER TABLE "PlanVersion" ADD CONSTRAINT "PlanVersion_prices_positive"
    CHECK (("priceMonthly" IS NULL OR "priceMonthly" > 0) AND ("priceYearly" IS NULL OR "priceYearly" > 0));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  ALTER TABLE "CreditPack" ADD CONSTRAINT "CreditPack_positive" CHECK ("price" > 0 AND "credits" > 0);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  ALTER TABLE "PaymentRequest" ADD CONSTRAINT "PaymentRequest_expected_positive" CHECK ("expectedAmount" > 0);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
"""
sys.stdout.write(hdr + "\n\n".join(out) + "\n" + extra)
